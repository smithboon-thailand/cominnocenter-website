/**
 * ฟอนต์เสริมสำหรับอักษรจีน — **ข้อยกเว้นเดียวของกฎ "Kanit ตระกูลเดียวทั้งเว็บ"**
 * (BRAND.md PART C v1.3 — ผู้ใช้อนุมัติ 24 ก.ย. 2569 ตอนเพิ่มภาษาจีน)
 *
 * Kanit ไม่มีอักษรจีนเลย ถ้าไม่ระบุฟอนต์สำรอง เบราว์เซอร์แต่ละเครื่องจะหยิบ
 * ฟอนต์จีนของระบบมาเองซึ่งน้ำหนักและสัดส่วนต่างกันมาก (Windows ไม่มีน้ำหนัก 500
 * ให้ Microsoft YaHei หัวเรื่องจึงหนาเท่าเนื้อหา) — Noto Sans SC เป็นตระกูล
 * เดียวกับที่ Google ออกแบบให้เข้าคู่กับ sans ละติน มีน้ำหนัก 400/500 ครบ
 * และ self-host ผ่าน next/font เหมือน Kanit จึงไม่ต้องเพิ่มโดเมนใน CSP
 *
 * **ทำไมแยกไฟล์จาก `fonts.ts`** — next/font ฝัง `@font-face` ลงใน CSS chunk ของ
 * route ที่ import โมดูลนั้น ฟอนต์จีนถูกหั่นตาม unicode-range เป็น **203 บล็อก
 * (185 KB ของ CSS)** ตอนที่อยู่ไฟล์เดียวกับ Kanit ทุกหน้าไทยและอังกฤษก็ต้องโหลด
 * CSS ก้อนนั้นไปด้วยทั้งที่ไม่มีอักษรจีนสักตัว (วัดจาก build 24 ก.ย. 2569:
 * ไฟล์ CSS ของฟอนต์โตจากไม่กี่ร้อยไบต์เป็น 185 KB และถูกลิงก์จาก / ด้วย)
 * แยกออกมาให้เฉพาะ `(zh)/layout.tsx` กับหน้า 404 จีน import จึงเหลือเฉพาะหน้าจีน
 *
 * กติกาใช้งาน:
 * - ใช้**เฉพาะ route group (zh)** ผ่านกฎ CSS ที่ผูกกับ `html[lang="zh-Hans"]`
 *   ใน globals.css · หน้าไทยและอังกฤษไม่โหลดทั้ง CSS และไฟล์ฟอนต์ชุดนี้
 * - อยู่**หลัง** Kanit ในลำดับ font-family เสมอ — ตัวเลข ละติน และเครื่องหมาย
 *   วรรคตอนละตินยังเป็น Kanit เหมือนทุกหน้า มีแต่อักษรจีนที่ตกมาถึงฟอนต์นี้
 * - น้ำหนัก 400/500 เท่านั้น ตามกฎเดียวกับ Kanit
 *
 * `preload: false` เพราะ Google Fonts หั่นฟอนต์จีนเป็นชิ้นตาม unicode-range
 * กว่าร้อยไฟล์ต่อน้ำหนัก เบราว์เซอร์จะโหลดเฉพาะชิ้นที่หน้านั้นใช้จริง
 * การ preload ทุกชิ้นตั้งแต่เปิดหน้าจึงเป็นการโหลดเปล่าเกือบทั้งหมด
 * (ตรวจแล้ว: หน้าจีนไม่มี <link rel="preload" as="font"> ของ Noto เลย)
 */
export const notoSansSC = Noto_Sans_SC({
  weight: ["400", "500"],
  variable: "--font-noto-sc",
  display: "swap",
  preload: false,
});
