/**
 * เงื่อนไขว่าจะเปิด Google Analytics หรือไม่ — ใช้ร่วมกันทั้งแถบความยินยอม
 * และปุ่มตั้งค่าท้ายเว็บ เพื่อให้สองที่ตัดสินใจตรงกันเสมอ
 *
 * ค่าทั้งสองเป็น NEXT_PUBLIC_ จึงถูกฝังลงบันเดิลตอน build
 * (ทุกหน้าเป็น static — เปลี่ยนค่าแล้ว **ต้อง redeploy** ถึงจะมีผล)
 */

/**
 * Measurement ID ของ GA4 — stream ชื่อ "Cominno"
 *
 * ใส่ในโค้ดตรงๆ ได้เพราะไม่ใช่ความลับ: รหัสนี้ปรากฏใน HTML ของทุกเว็บที่ใช้ GA
 * อยู่แล้ว และตัวมันเองไม่ให้สิทธิ์เข้าถึงรายงานในบัญชี GA ของศูนย์ฯ
 *
 * ใส่ในโค้ดแทนการตั้ง env var ที่ Vercel เพื่อลดขั้นตอนที่พลาดได้ (ต้องจำว่า
 * ติ๊กเฉพาะ Production และต้อง redeploy) — env var ยังใช้ทับได้ถ้าต้องเปลี่ยน
 *
 * ผลข้างเคียงที่ต้องกันเพิ่ม: พอค่าอยู่ในโค้ด มันจะติดไปทุกที่ที่โค้ดรัน
 * รวมถึงเครื่องของคนพัฒนา จึงมีตัวกัน IS_DEV ด้านล่างคู่กับตัวกัน preview
 */
export const GA_ID = process.env.NEXT_PUBLIC_GA_ID || "G-B15Y4D0DLJ";

/**
 * ปิด GA ตอนรัน `npm run dev`
 *
 * จำเป็นเพราะรหัส GA อยู่ในโค้ดแล้ว ไม่ได้มาจาก env var ที่ตั้งเฉพาะ production
 * ถ้าไม่กันไว้ ทุกครั้งที่มีคนเปิดเว็บในเครื่องแล้วกดยอมรับ จะถูกนับเป็นผู้เข้าชม
 * เว็บจริง — ปัญหาเดียวกับ preview แต่คนละต้นตอ
 */
const IS_DEV = process.env.NODE_ENV !== "production";

/**
 * ปิด GA บน preview deployment ของ Vercel
 *
 * เหตุผล: ทุก branch ที่ push ได้ preview URL อัตโนมัติ ถ้า GA ทำงานที่นั่นด้วย
 * ทุกครั้งที่เราเปิด preview ตรวจงานจะถูกนับเป็นผู้เข้าชมเว็บจริง สถิติของศูนย์ฯ
 * จะเพี้ยนโดยไม่มีใครรู้ตัว และแยกออกทีหลังไม่ได้เพราะ GA4 ลบข้อมูลย้อนหลังไม่ได้
 *
 * ทำไมต้องมีตัวกันชั้นนี้ทั้งที่ตั้ง env var เฉพาะ Production ก็พอ:
 * ตอนเพิ่มตัวแปรใน Vercel ระบบ**ติ๊กครบทั้งสามสภาพแวดล้อมให้เป็นค่าเริ่มต้น**
 * (Production / Preview / Development) คนที่กดผ่านเร็วๆ จะได้ค่าที่เก็บ preview
 * ไปด้วยทันที ชั้นนี้กันความผิดพลาดนั้นไว้ไม่ว่าจะตั้งค่ามาแบบไหน
 *
 * เช็คว่าเท่ากับ "preview" ไม่ใช่เช็คว่าเท่ากับ "production" โดยตั้งใจ —
 * ถ้าวันหนึ่งย้ายออกจาก Vercel ตัวแปรนี้จะหายไปเป็น undefined ซึ่งไม่เท่ากับ
 * "preview" GA จึงยังทำงานตามปกติ ไม่ดับเงียบๆ โดยไม่มีใครสังเกต
 */
const IS_VERCEL_PREVIEW = process.env.NEXT_PUBLIC_VERCEL_ENV === "preview";

/** โหลดสคริปต์ gtag จริงหรือไม่ — ต้องมีรหัส ไม่ใช่ preview และไม่ใช่เครื่องพัฒนา */
export const analyticsEnabled = Boolean(GA_ID) && !IS_VERCEL_PREVIEW && !IS_DEV;

/**
 * แสดงแถบขอความยินยอมหรือไม่ — แยกจาก analyticsEnabled โดยตั้งใจ
 *
 * ปัญหาที่แก้ (31 ส.ค. 2569): ตอนแรกผูกสองเรื่องนี้เป็นเงื่อนไขเดียวกัน ผลคือ
 * บน preview ไม่มีแถบขึ้นเลย **ผู้ใช้จึงตรวจฟีเจอร์นี้ก่อน merge ไม่ได้**
 * ซึ่งขัดกับกติกาข้อ 2 ของโปรเจ็คที่ทุกอย่างต้องผ่านการตรวจ Preview ก่อน
 *
 * แยกออกจากกันแล้วได้ทั้งสองอย่าง: บน preview แถบขึ้นให้ตรวจหน้าตาและการกดได้
 * ครบ แต่ gtag ไม่โหลด สถิติจึงไม่เพี้ยน · ไม่ต้องตั้ง env var บน preview เลย
 *
 * ข้อแลกเปลี่ยนที่ยอมรับ: บน preview การกด "ยอมรับ" จะไม่มีอะไรเกิดขึ้นจริง
 * เป็นแค่การแสดงผล — รับได้เพราะ preview มีแต่ทีมงานเข้า ไม่ใช่ผู้ใช้จริง
 */
export const consentBannerEnabled = analyticsEnabled || IS_VERCEL_PREVIEW;
