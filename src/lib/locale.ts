/**
 * ภาษาของหน้าเว็บ — แหล่งความจริงเดียวของชนิด `Locale`
 *
 * ทำไมต้องมีไฟล์นี้ (24 ก.ย. 2569)
 *
 * ก่อนเพิ่มภาษาจีน ชนิด `"th" | "en"` ถูกพิมพ์ซ้ำอยู่ **36 ไฟล์** ทั้งใน
 * component · lib · data การเพิ่มภาษาที่สามจึงต้องไล่แก้ทุกไฟล์พร้อมกัน และ
 * ไฟล์ไหนตกหล่นจะไม่มีอะไรฟ้องจนกว่าจะมีหน้าจีนส่งค่า `"zh"` เข้าไป
 * รวมไว้ที่เดียวแล้ว ครั้งหน้าเพิ่มภาษาที่สี่ก็แก้บรรทัดเดียว
 *
 * **`zh` = จีนตัวย่อ (Simplified Chinese)** ตามที่ผู้ใช้ตัดสินใจ 24 ก.ย. 2569
 * ใน URL ใช้ `/zh` สั้นๆ ส่วน `<html lang>` และ hreflang ใช้ `zh-Hans` เต็ม
 * เพราะเบราว์เซอร์และเสิร์ชเอนจินต้องแยกตัวย่อออกจากตัวเต็ม (`zh-Hant`)
 *
 * **ภาษาจีนมีเฉพาะหน้าหลักและหน้าโครงการ** — ไม่มีข่าว สื่อถึงเรา และหน้าบทสรุป
 * งานวิจัย (ตกลงกับผู้ใช้แล้ว: ข่าวเป็นเนื้อหาเก่าที่ผูกกับเวลา ส่วนบทสรุป 62 ชิ้น
 * จะทยอยแปลเป็นชุดใน PR ถัดไป) component ที่รับ `Locale` เต็มจึงต้องไม่ลิงก์ไป
 * เส้นทางเหล่านั้นเมื่อ locale เป็น `zh` — `check:routes` จะฟ้องถ้าหลุด
 */
export type Locale = "th" | "en" | "zh";

/**
 * ภาษาที่**มีเนื้อหาครบทุกหน้า** — ใช้กับส่วนที่ยังไม่มีฉบับจีน
 * (บทสรุปงานวิจัย · ข่าว · สื่อถึงเรา · วิดีโอ)
 */
export type FullLocale = "th" | "en";

/** ค่า `<html lang>` และ hreflang ของแต่ละภาษา */
export const HTML_LANG: Record<Locale, string> = {
  th: "th",
  en: "en",
  zh: "zh-Hans",
};

/** คำนำหน้า path ของแต่ละภาษา — ไทยอยู่ที่ root จึงเป็นสตริงว่าง */
export const LOCALE_PREFIX: Record<Locale, string> = {
  th: "",
  en: "/en",
  zh: "/zh",
};

/** path ของหน้าเดียวกันในภาษาอื่น เช่น localePath("zh", "/about") → "/zh/about" */
export function localePath(locale: Locale, path: string): string {
  const prefix = LOCALE_PREFIX[locale];
  if (path === "/" || path === "") return prefix || "/";
  return `${prefix}${path}`;
}
